/**
 * ClickHouse async batch writer for usage logs (official @clickhouse/client SDK).
 *
 * Positioning: **Self-hosted / Cloud ClickHouse usage reporting**, used to show token consumption per user (by turn).
 * Independent of Langfuse / Opik reporting — Langfuse handles trace visualization, while ClickHouse acts as usage/billing data source.
 *
 * Features:
 * - Official SDK (createClient + insert(JSONEachRow) + command(DDL))
 * - In-memory buffer + periodic/threshold flush
 * - Retry queue on failure (with buffer cap to prevent OOM)
 * - Error-silent: never blocks or degrades business requests
 * - Graceful shutdown: flushes remaining buffer before exit
 *
 * Reliability note: Failed rows are requeued and retried, but when buffer exceeds cap, oldest rows are dropped ("best-effort" rather than
 * "zero-loss"). If billing requires zero-loss, persistent WAL must be added in future — not implemented currently.
 */

