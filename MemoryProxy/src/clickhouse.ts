/** Compute first 16 hex characters of body sha256 (for TopN GROUP BY deduplication). Returns empty string for empty body. */
function bodyHash16(body: string): string {
  if (!body) return "";
  return createHash("sha256").update(body).digest("hex").slice(0, 16);
}

