export async function createTableIfNotExists(
  ch: ClickHouseClient,
  ddl: string,
): Promise<void> {
  await ch.command({
    query: ddl,
    clickhouse_settings: { wait_end_of_query: 1 },
  });
}

/**
 * Generic enqueue + threshold-triggered flush (fire-and-forget).
 *
 * - Two-layer internal try/catch: one push fallback, one flushFn throw (async Promise unawaited).
 * - Never throws to caller.
 */
export function enqueueRow<T>(
  buf: T[],
  row: T,
  flushFn: () => Promise<void>,
  threshold: number,
): void {
  try {
    buf.push(row);
    if (buf.length >= threshold) {
      // fire-and-forget; error logged in flushBuffer, with .catch() fallback
      void flushFn().catch(() => { /* never throw */ });
    }
  } catch {
    // Extreme case: buffer itself corrupted — keep business logic unaffected
  }
}

/**
 * Generic flush: drain buffer → batch insert → call requeueFn on failure.
 *
 * - no-op when client is null / buf is empty
 * - buf emptied via splice(0) on success
 * - on failure rows extracted from buf → passed to requeueFn; resolves (does not reject) after log.error
 */
export async function flushBuffer<T>(
  buf: T[],
  ch: ClickHouseClient | null,
  tableName: string,
  requeueFn: (rows: T[]) => void,
  logLabel: string,
): Promise<void> {
  if (!ch || buf.length === 0) return;
  const rows = buf.splice(0);
  try {
    await ch.insert({
      table: tableName,
      values: rows,
      format: "JSONEachRow",
      clickhouse_settings: { async_insert: 1, wait_for_async_insert: 1 },
    });
    log.debug(`${logLabel}.flush.ok`, { rows: rows.length });
  } catch (err: unknown) {
    log.error(
      `${logLabel}.flush.error`,
      { rows: rows.length },
      err instanceof Error ? err : new Error(String(err)),
    );
    try {
      requeueFn(rows);
    } catch {
      // requeue also failed → discard; at least avoid rethrowing and dragging down business logic
    }
  }
}

/**
 * Re-queue + overflow protection: when buffer exceeds 10,000, drop oldest half and keep 5,000.
 *
 * Return value is new buffer reference (may be same array or newly sliced array).
 * Caller must reassign return value back to their buffer variable.
 */
export function requeueWithOverflowGuard<T>(
  buf: T[],
  failedRows: T[],
  logLabel: string,
): T[] {
  try {
    buf.unshift(...failedRows);
    if (buf.length > 10000) {
      const dropped = buf.length - 5000;
      const trimmed = buf.slice(buf.length - 5000);
      log.warn(logLabel, { dropped });
      return trimmed;
    }
    return buf;
  } catch {
    return buf;
  }
}

